.TITLE
    Remediation - Repair Disk File System

.SYNOPSIS
    Scans the system drive file system with Repair-Volume and reports the outcome.

.DESCRIPTION
    Paired remediation for Repair-Disk. Runs every time detect-Repair-Disk.ps1
    returns exit 1 (the detector is an unconditional trigger). Resolves the system
    drive letter, runs `Repair-Volume -Scan`, flattens verbose scan output into one
    status string, and compares it to the expected healthy token. Performs:
    (1) pre-remediation validation, (2) scan with failure tracking, (3) post-check
    against the healthy token, (4) structured JSON result output for Intune
    diagnostics.

    Exit contract:
    Exit 0 = success (scan output matched the expected healthy value)
    Exit 1 = failure (scan output indicated issues or the check failed)
    Exit 2 = script error

.TAGS
    Remediation,Action,Disk,FileSystem

.REMEDIATIONTYPE
    Remediation

.PAIRSCRIPT
    detect-Repair-Disk.ps1

.PLATFORM

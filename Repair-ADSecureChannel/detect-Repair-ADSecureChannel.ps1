<#
.TITLE
    Detection - Active Directory Secure Channel

.SYNOPSIS
    Verifies that the computer secure channel to the Active Directory domain is healthy.

.DESCRIPTION
    Evaluates whether the device is domain-joined and, when it is, tests the machine
    secure channel with Test-ComputerSecureChannel. A broken secure channel blocks
    domain authentication, Group Policy application, and domain-based Intune
    co-management, so enterprise baselines require it healthy. Devices that are not
    domain-joined are compliant by definition (not applicable). This script NEVER
    modifies the system.

    Exit contract:
    Exit 0 = compliant (no remediation needed)
    Exit 1 = non-compliant (Intune runs the paired remediation)
    Exit 2 = script error (Intune must NOT treat a crash as non-compliance)

.TAGS
    Remediation,Detection,ActiveDirectory,SecureChannel

.REMEDIATIONTYPE
    Detection

.PAIRSCRIPT
    remediate-Repair-ADSecureChannel.ps1

.PLATFORM
